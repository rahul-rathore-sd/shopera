const slugify = (value) =>
  value
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, "")
    .replace(/[\s_-]+/g, "-")
    .replace(/^-+|-+$/g, "");

async function seedCategories() {
  const categoryMap = new Map();

  for (const cat of categoriesData) {
    const slug = slugify(cat.name);
    const categoryDoc = await Category.findOneAndUpdate(
      { slug },
      {
        $set: {
          name: cat.name,
          slug,
          description: cat.description,
          isActive: true,
        },
      },
      { upsert: true, returnDocument: "after", runValidators: true }
    );
    categoryMap.set(cat.name, categoryDoc._id);
  }

  // Remove any legacy categories not in the active catalog list
  const validCategorySlugs = categoriesData.map((c) => slugify(c.name));
  await Category.deleteMany({ slug: { $nin: validCategorySlugs } });

  console.log(`✓ Seeded ${categoryMap.size} product categories.`);
  return categoryMap;
}

export async function seedProducts({ isStandalone = false, force = true } = {}) {
  if (!process.env.MONGO_URI && mongoose.connection.readyState === 0) {
    throw new Error("MONGO_URI environment variable is missing.");
  }

  console.log("=== STARTING 105-PRODUCT CATALOG SEEDING (15 PER CATEGORY) ===");
  if (mongoose.connection.readyState === 0) {
    await mongoose.connect(process.env.MONGO_URI);
  }

  const categoryMap = await seedCategories();

  // Clear existing products to ensure clean catalog with full fields if force=true
  if (force) {
    const deleteResult = await Product.deleteMany({});
    console.log(`✓ Cleared ${deleteResult.deletedCount} previous products.`);
  }

  const productsToInsert = productsData.map((p) => {
    const slug = slugify(p.title);
    const categoryId = categoryMap.get(p.category);

    if (!categoryId) {
      throw new Error(`Category not found for product: ${p.title} (category: ${p.category})`);
    }

    return {
      title: p.title,
      slug,
      description: p.description,
      brand: p.brand,
      category: categoryId,
      images: p.images,
      basePrice: p.basePrice,
      baseDiscountPrice: p.baseDiscountPrice,
      stock: p.stock,
      hasVariants: p.hasVariants || false,
      variants: p.variants || [],
      ratingsAverage: p.ratingsAverage,
      ratingsQuantity: p.ratingsQuantity,
      tags: p.tags || [],
      isPublished: true,
      featured: p.featured || false,
    };
  });

  const inserted = await Product.insertMany(productsToInsert);
  console.log(`🎉 SUCCESS: Seeded ${inserted.length} rich products directly into Database!`);

  // Print summary by category
  const counts = await Product.aggregate([
    {
      $group: {
        _id: "$category",
        count: { $sum: 1 },
      },
    },
  ]);

  console.log("=== PRODUCT DISTRIBUTION ===");
  for (const c of counts) {
    const cat = await Category.findById(c._id);
    console.log(`- ${cat?.name || "Other"}: ${c.count} products`);
  }

  if (isStandalone) {
    await mongoose.disconnect();
    console.log("✓ MongoDB Disconnected");
  }

  return { categoriesCount: categoryMap.size, productsCount: inserted.length };
}

export async function autoSeedIfEmpty() {
  try {
    const productCount = await Product.countDocuments();
    if (productCount === 0) {
      console.log("⚡ Database is empty on startup. Auto-seeding 105 catalog products...");
      await seedProducts({ isStandalone: false, force: false });
    } else {
      console.log(`✓ Live database has ${productCount} products.`);
    }
  } catch (err) {
    console.error("⚠️ Auto-seed check warning:", err.message);
  }
}

