if (process.argv[1] && process.argv[1].replace(/\\/g, "/").endsWith("seedProducts.js")) {
  seedProducts({ isStandalone: true, force: true })
    .catch((err) => {
      console.error("❌ Seed failed:", err);
      process.exitCode = 1;
    });
}
